"""Run every payload against every pattern and write benchmark/results.md.

This is what turns the repo from six opinions into a table. Same attacks, same
verdict function, six architectures.
"""

from __future__ import annotations

import argparse
import importlib
import sys
import time
from dataclasses import dataclass
from pathlib import Path

from attacks.payloads import PAYLOADS
from core.verdict import is_compromised

PATTERNS = [
    ("p01_action_selector", "Action-Selector", "Fixed action list"),
    ("p02_plan_then_execute", "Plan-Then-Execute", "Frozen plan"),
    ("p03_llm_map_reduce", "LLM Map-Reduce", "Map-output sanitizer"),
    ("p04_dual_llm", "Dual LLM", "Privileged LLM + symbolic memory"),
    ("p05_code_then_execute", "Code-Then-Execute", "Execution sandbox"),
    ("p06_context_minimization", "Context-Minimization", "Context pruner"),
]

NOTES = {
    "p01_action_selector": "Immune by construction to tool hijacking: the tool is not in the enum.",
    "p02_plan_then_execute": "Plan holds; the *content* of a planned step can still be coloured. Known residual risk.",
    "p03_llm_map_reduce": "Hijacked worker output fails validation and is dropped before the reduce.",
    "p04_dual_llm": "Strongest separation: the payload never enters the privileged context at all.",
    "p05_code_then_execute": "AST allowlist rejects the program before the interpreter sees it.",
    "p06_context_minimization": "Bounds an injection to one turn; does not prevent that turn.",
}


@dataclass
class Row:
    pattern: str
    payload_id: str
    insecure: str
    secure: str
    why_secure: str
    latency_ms: float


def run_all() -> list[Row]:
    rows: list[Row] = []
    for module_name, label, _guardian in PATTERNS:
        insecure = importlib.import_module(f"patterns.{module_name}.insecure_agent")
        secure = importlib.import_module(f"patterns.{module_name}.secure_agent")

        # Warm up so the first payload is not billed for import and regex compilation.
        secure.run_payload(PAYLOADS[0])

        for payload in PAYLOADS:
            bad_i, _ = is_compromised(payload, insecure.run_payload(payload))
            start = time.perf_counter()
            bad_s, why_s = is_compromised(payload, secure.run_payload(payload))
            rows.append(
                Row(
                    pattern=label,
                    payload_id=payload.id,
                    insecure="compromised" if bad_i else "safe",
                    secure="compromised" if bad_s else "safe",
                    why_secure=why_s,
                    latency_ms=round((time.perf_counter() - start) * 1000, 2),
                )
            )
    return rows


def summarise(rows: list[Row]) -> dict[str, tuple[int, int, int]]:
    """pattern -> (blocked_secure, blocked_insecure, total)"""
    out: dict[str, tuple[int, int, int]] = {}
    for _module, label, _guardian in PATTERNS:
        subset = [r for r in rows if r.pattern == label]
        out[label] = (
            sum(r.secure == "safe" for r in subset),
            sum(r.insecure == "safe" for r in subset),
            len(subset),
        )
    return out


def render(rows: list[Row]) -> str:
    summary = summarise(rows)
    total = len(PAYLOADS)
    lines = [
        "# Benchmark results",
        "",
        "Generated by `python -m benchmark.run_all`. Every pattern is scored by the",
        "same `core.verdict.is_compromised` against the same six payloads in",
        "`attacks/payloads.py`. Numbers are attacks **blocked**, higher is better.",
        "",
        "| Pattern | Guardian | Secure | Insecure | Note |",
        "|---|---|---:|---:|---|",
    ]
    for module_name, label, guardian in PATTERNS:
        blocked_s, blocked_i, _ = summary[label]
        lines.append(
            f"| {label} | {guardian} | **{blocked_s}/{total}** | {blocked_i}/{total} | {NOTES[module_name]} |"
        )

    lines += ["", "## Per-payload detail", "",
              "| Pattern | Payload | Insecure | Secure | Verdict (secure) | ms |",
              "|---|---|---|---|---|---:|"]
    for row in rows:
        mark_i = "compromised" if row.insecure == "compromised" else "safe"
        mark_s = "compromised" if row.secure == "compromised" else "**safe**"
        lines.append(
            f"| {row.pattern} | `{row.payload_id}` | {mark_i} | {mark_s} | {row.why_secure} | {row.latency_ms} |"
        )
    lines += [
        "",
        "> No pattern scores 6/6 by accident. Where a number is below the maximum it is",
        "> a residual risk the pattern is *known* not to cover - documented in that",
        "> pattern's README rather than engineered away in the benchmark.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Run the full attack/defence matrix.")
    parser.add_argument("--check", action="store_true", help="fail if any pattern regressed")
    parser.add_argument("--out", default="benchmark/results.md")
    args = parser.parse_args()

    rows = run_all()
    Path(args.out).write_text(render(rows), encoding="utf-8")
    summary = summarise(rows)

    print(f"\n  {'pattern':<24} {'secure':>8} {'insecure':>10}")
    for label, (blocked_s, blocked_i, total) in summary.items():
        print(f"  {label:<24} {blocked_s:>4}/{total}   {blocked_i:>4}/{total}")
    print(f"\n  wrote {args.out}\n")

    if args.check:
        failures = [
            label for label, (s, i, _t) in summary.items() if s <= i or s == 0
        ]
        if failures:
            print(f"  REGRESSION in: {', '.join(failures)}", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
