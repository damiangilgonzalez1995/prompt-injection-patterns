"""Record what was actually sent to the model, and what came back.

The benchmark tells you *that* a pattern held. This tells you *why*, by showing
the receipts: every prompt, every response, every tool that fired, side by side
without the pattern and with it.

    python -m benchmark.capture_transcripts             # all patterns
    python -m benchmark.capture_transcripts --pattern p04_dual_llm
    TEST_MODE=live python -m benchmark.capture_transcripts   # against a real model

In mock mode the model is `InjectableMockLLM`, which obeys any injection it can
see - a faithful stand-in for a compliant model, and free. In live mode nothing
is scripted: whether the model swallows the payload is the model's decision, and
these files are the evidence either way.
"""

from __future__ import annotations

import argparse
import importlib
import os
from pathlib import Path

from attacks.payloads import PAYLOADS, Payload
from core import llm as llm_module
from core.agent import AgentRun
from core.verdict import is_compromised

OUT_DIR = Path("docs/transcripts")

PATTERNS = [
    ("p01_action_selector", "Action-Selector", "fixed action list"),
    ("p02_plan_then_execute", "Plan-Then-Execute", "frozen plan"),
    ("p03_llm_map_reduce", "LLM Map-Reduce", "map-output sanitizer"),
    ("p04_dual_llm", "Dual LLM", "privileged LLM + symbolic memory"),
    ("p05_code_then_execute", "Code-Then-Execute", "execution sandbox"),
    ("p06_context_minimization", "Context-Minimization", "context pruner"),
]


def _mode() -> tuple[str, str]:
    if os.getenv("TEST_MODE", "mock").lower() == "live":
        provider = os.getenv("LLM_PROVIDER", "openai").lower()
        model = os.getenv(
            "ANTHROPIC_MODEL" if provider == "anthropic" else "OPENAI_MODEL", "gpt-4o-mini"
        )
        return "live", f"{provider}:{model}"
    return "mock", "InjectableMockLLM (offline, obeys any injection it can see)"


def _fence(text: str, lang: str = "text") -> str:
    return f"```{lang}\n{text.strip()}\n```"


def _capture(fn, payload: Payload) -> tuple[AgentRun, list]:
    llm_module.reset_transcript()
    run = fn(payload)
    return run, list(llm_module.TRANSCRIPT)


def _render_side(title: str, run: AgentRun, calls: list, payload: Payload) -> list[str]:
    compromised, why = is_compromised(payload, run)
    badge = "**COMPROMISED**" if compromised else "**BLOCKED**"

    lines = [f"#### {title} - {badge}", ""]

    for i, call in enumerate(calls, 1):
        saw = payload.marker in call.prompt.full()
        ate = call.hijacked_by is not None
        label = f"call {i} - `{call.llm_name}`"
        flags = []
        flags.append("payload IS in this prompt" if saw else "payload is NOT in this prompt")
        if ate:
            flags.append("**the model ate it**")
        lines += [f"<details><summary>{label} - {', '.join(flags)}</summary>", ""]
        lines += ["*system prompt sent:*", _fence(call.prompt.system), ""]
        lines += ["*user turn sent:*", _fence(call.prompt.user), ""]
        lines += ["*model replied:*", _fence(call.output), "", "</details>", ""]

    if not calls:
        lines += ["*(no model call reached this stage)*", ""]

    tools = ", ".join(str(c) for c in run.tool_calls) or "none"
    lines += [
        f"**Tools executed:** {tools}",
        "",
        f"**Answer returned to the user:**",
        _fence(run.answer),
        "",
        f"**Verdict:** {badge} - {why}",
        "",
    ]
    return lines


def render_pattern(module_name: str, label: str, guardian: str) -> str:
    insecure = importlib.import_module(f"patterns.{module_name}.insecure_agent")
    secure = importlib.import_module(f"patterns.{module_name}.secure_agent")
    mode, model = _mode()

    lines = [
        f"# Transcripts - {label}",
        "",
        f"Guardian: **{guardian}** · Mode: `{mode}` · Model: `{model}`",
        "",
        "Generated by `python -m benchmark.capture_transcripts`. Both columns run",
        "on the **same model**: the difference below is architecture, not prompting.",
        "",
        f"Pattern reference: [`patterns/{module_name}/README.md`](../../patterns/{module_name}/README.md)",
        "",
        "---",
        "",
    ]

    for payload in PAYLOADS:
        run_i, calls_i = _capture(insecure.run_payload, payload)
        run_s, calls_s = _capture(secure.run_payload, payload)

        lines += [
            f"## Attack: `{payload.id}`",
            "",
            f"Category `{payload.category}` · target `{payload.target}`",
            "",
            "**The payload, as the attacker plants it:**",
            _fence(payload.text),
            "",
            f"**Expected of a secure agent:** {payload.expected_secure_behavior}",
            "",
        ]
        lines += _render_side("WITHOUT the pattern (`insecure_agent.py`)", run_i, calls_i, payload)
        lines += _render_side("WITH the pattern (`secure_agent.py`)", run_s, calls_s, payload)
        lines += ["---", ""]

    return "\n".join(lines)


def render_index() -> str:
    mode, model = _mode()
    lines = [
        "# Transcripts",
        "",
        "What actually went to the model, and what came back - for every pattern",
        "against every payload, without the defence and with it.",
        "",
        f"Current capture: mode `{mode}`, model `{model}`.",
        "",
        "| Pattern | Guardian | Transcript |",
        "|---|---|---|",
    ]
    for module_name, label, guardian in PATTERNS:
        lines.append(f"| {label} | {guardian} | [`{module_name}.md`]({module_name}.md) |")
    lines += [
        "",
        "## Regenerate",
        "",
        "```bash",
        "# offline, deterministic, free (default)",
        "python -m benchmark.capture_transcripts",
        "",
        "# against a real model - needs a key in .env",
        "pip install -e '.[llm]'",
        "TEST_MODE=live python -m benchmark.capture_transcripts",
        "```",
        "",
        "## How to read these",
        "",
        "Each call is collapsed into a `<details>` block that states two things",
        "before you open it:",
        "",
        "- **payload IS / is NOT in this prompt** - did untrusted text reach this",
        "  context at all? This is the architectural question. Dual LLM and",
        "  Context-Minimization win here: the payload is simply never present.",
        "- **the model ate it** - given that the payload was present, did the model",
        "  follow it? In mock mode the answer is always yes, by construction. In",
        "  live mode it is the real model's decision.",
        "",
        "The second line is why the first line matters. A defence that depends on",
        "the model *not* eating a payload it can see is a defence that works until",
        "the day it doesn't. A defence that keeps the payload out of the context",
        "does not have that failure mode.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pattern", help="capture one pattern only, e.g. p04_dual_llm")
    args = parser.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    selected = [p for p in PATTERNS if not args.pattern or p[0] == args.pattern]
    if not selected:
        print(f"unknown pattern: {args.pattern}")
        return 1

    for module_name, label, guardian in selected:
        path = OUT_DIR / f"{module_name}.md"
        path.write_text(render_pattern(module_name, label, guardian), encoding="utf-8")
        print(f"  wrote {path}")

    (OUT_DIR / "README.md").write_text(render_index(), encoding="utf-8")
    print(f"  wrote {OUT_DIR / 'README.md'}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
